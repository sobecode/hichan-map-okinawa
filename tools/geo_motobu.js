const sleep = ms => new Promise(r => setTimeout(r, ms));

(async () => {
  const out = [];
  for (const [name, addr] of rows) {
    const url = 'https://msearch.gsi.go.jp/address-search/AddressSearch?q=' + encodeURIComponent(addr);
    let rec = { name, addr, lat: null, lng: null, hit: null };
    try {
      const res = await fetch(url);
      const j = await res.json();
      if (j && j.length) {
        // 最も詳細（title が長い＝番地まで一致）なものを採る
        const best = j.reduce((a, b) => (b.properties.title.length > a.properties.title.length ? b : a));
        rec.lng = best.geometry.coordinates[0];
        rec.lat = best.geometry.coordinates[1];
        rec.hit = best.properties.title;
      }
    } catch (e) { rec.err = String(e); }
    out.push(rec);
    console.log([name, rec.lat, rec.lng, rec.hit].join(' | '));
    await sleep(400);
  }
  fs.writeFileSync(__dirname + '/geo_motobu.json', JSON.stringify(out, null, 1));
})();
