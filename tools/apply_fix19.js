const NAME_RE = /\{n:'((?:[^'\\]|\\.)*)'/;

const lines = fs.readFileSync(P, 'utf8').split('\n');
const done = [], skipped = [];
for (const [name, newA, newLL] of FIX) {
  let hit = false;
  for (let i = 0; i < lines.length; i++) {
    const L = lines[i];
    if (!/^\s*\{n:'/.test(L)) continue;
    const m = NAME_RE.exec(L);
    if (!m || m[1] !== name) continue;
    let out = L;
    if (newA)  out = out.replace(/,a:'(?:[^'\\]|\\.)*'/, `,a:'${newA}'`);
    if (newLL) out = out.replace(/,lat:-?[\d.]+,lng:-?[\d.]+,/, `,lat:${newLL[0]},lng:${newLL[1]},`);
    hit = true;
    // 既に反映済みなら何も変わらない。何度実行しても同じ結果になるようにする
    if (out === L) { skipped.push(name); break; }
    lines[i] = out;
    done.push(`${name}  ${newA ? 'a→' + newA + '  ' : ''}${newLL ? '座標→' + newLL.join(',') : ''}`);
    break;
  }
  if (!hit) throw new Error('見つからない: ' + name);
}
fs.writeFileSync(P, lines.join('\n'), 'utf8');
console.log('修正 ' + done.length + ' 件 / 反映済みで変更なし ' + skipped.length + ' 件');
